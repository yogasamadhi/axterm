export type AxtermMessageKey = keyof (typeof axtermMessages)['en'];
export type Variables = Readonly<Record<string, string | number>>;

function interpolate(message: string, variables?: Variables): string {
  if (!variables) return message;
  return message.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/gu, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match,
  );
}

export const APP_LOCALES: readonly LocaleDefinition[] = localeData.locales;
export const ELECTERM_LOCALE_SOURCE = localeData.source;
export const ELECTERM_LOCALE_KEY_COUNT = localeData.keyCount;

export function normalizeAppLanguage(value: string | null | undefined): AppLanguage | undefined {
  if (!value) return undefined;
  const normalized = value.trim().replaceAll('_', '-').toLowerCase();
  const exact = APP_LOCALES.find(({ id }) => id.toLowerCase() === normalized);
  if (exact) return exact.id;
  if (normalized === 'pt' || normalized.startsWith('pt-')) return 'pt-BR';
  if (/^zh-(tw|hk)(-|$)/u.test(normalized)) return 'zh-TW';
  if (/^zh-(cn|mo|sg)(-|$)/u.test(normalized) || normalized === 'zh') return 'zh-CN';
  return APP_LOCALES.find(({ id }) => id.toLowerCase() === normalized.split('-')[0])?.id;
}

export function resolveAppLanguage(languages: readonly string[]): AppLanguage {
  for (const value of languages) {
    const resolved = normalizeAppLanguage(value);
    if (resolved) return resolved;
  }
  return 'en';
}

export function languageDirection(language: AppLanguage): 'ltr' | 'rtl' {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function translateElecterm(
  language: AppLanguage,
  key: string,
  fallback = key,
  variables?: Variables,
): string {
  const selected = localeById.get(language)?.messages[key];
  return interpolate(selected ?? englishMessages[key] ?? fallback, variables);
}

export function translateAxterm(
  language: AppLanguage,
  key: AxtermMessageKey,
  variables?: Variables,
): string {
  const selected = language === 'zh-CN' ? axtermMessages['zh-CN'][key] : undefined;
  return interpolate(selected ?? axtermMessages.en[key], variables);
}
