import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(
  root,
  'vendor/electerm/node_modules/@electerm/electerm-themes/dist/index.mjs',
);
const outputPath = resolve(
  root,
  'packages/runtime/src/application/electerm-terminal-themes.generated.ts',
);

const source = await readFile(sourcePath, 'utf8');
if (!source.startsWith('export default [') || !source.trimEnd().endsWith(']')) {
  throw new Error(`Unexpected Electerm theme catalog format: ${sourcePath}`);
}

const generated = `${[
  '/* This file is generated by scripts/generate-electerm-themes.mjs. */',
  '/* Source: @electerm/electerm-themes@1.0.1 (MIT), vendored with Electerm. */',
  "/* Run 'bun run generate:electerm-themes' after updating the Electerm submodule. */",
  '',
].join('\n')}${source.replace(
  'export default [',
  'export const ELECTERM_TERMINAL_THEME_SOURCES: readonly string[] = [',
)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
console.log(`Generated ${outputPath.replace(`${root}/`, '')}`);
